// --- LOGIKA  ---

let currentImages = []; 
let currentIndex = 0;   

function searchKeyword() {
    const input = document.getElementById('searchInput').value.trim().toLowerCase();
    const errorMsg = document.getElementById('error-message');

    if (database[input]) {
        // Átirányít a result.html-re az adott ID-val
        window.location.href = `result.html?id=${input}`;
    } else {
        errorMsg.textContent = "Nincs találat.";
    }
}

// Enter gomb figyelése
const inputField = document.getElementById("searchInput");
if (inputField) {
    inputField.addEventListener("keypress", function(event) {
        if (event.key === "Enter") {
            searchKeyword();
        }
    });
}

function loadResult() {
    const params = new URLSearchParams(window.location.search);
    const id = params.get('id');
    const data = database[id];

    if (data) {
        document.getElementById('resultTitle').textContent = data.title;
        document.getElementById('resultText').textContent = data.text;

        
        if (Array.isArray(data.images)) {
            // -- GALÉRIA MÓD --
            currentImages = data.images;
            currentIndex = 0;
            
            document.querySelector('.prev-btn').style.display = 'block';
            document.querySelector('.next-btn').style.display = 'block';
            document.getElementById('image-counter').style.display = 'block';
            
            updateImage();
        } else {
            // -- SIMA KÉP MÓD --
            const imgSrc = data.image || data.images; 
            document.getElementById('resultImage').src = imgSrc;
            
            document.querySelector('.prev-btn').style.display = 'none';
            document.querySelector('.next-btn').style.display = 'none';
            document.getElementById('image-counter').style.display = 'none';
        }

    } else {
        document.getElementById('resultTitle').textContent = "Hiba";
        document.getElementById('resultText').textContent = "A tartalom nem található.";
    }
}

function changeSlide(direction) {
    currentIndex += direction;

    if (currentIndex >= currentImages.length) {
        currentIndex = 0;
    }
    if (currentIndex < 0) {
        currentIndex = currentImages.length - 1;
    }

    updateImage();
}

function updateImage() {
    const currentSrc = currentImages[currentIndex];
    
    const imgElement = document.getElementById('resultImage');
    const videoElement = document.getElementById('resultVideo');
    const counterElement = document.getElementById('image-counter');

    
    const isVideo = currentSrc.toLowerCase().endsWith('.mp4') || 
                    currentSrc.toLowerCase().endsWith('.mov') || 
                    currentSrc.toLowerCase().endsWith('.webm');

    if (isVideo) {
        
        imgElement.style.display = 'none';
        
        
        videoElement.src = currentSrc;
        videoElement.style.display = 'block';
        
       

    } else {
        
        videoElement.pause();
        videoElement.style.display = 'none';
        videoElement.src = ""; 

        
        imgElement.src = currentSrc;
        imgElement.style.display = 'block';
    }

    
    if (counterElement) {
        counterElement.textContent = (currentIndex + 1) + " / " + currentImages.length;
    }
}